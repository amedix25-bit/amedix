// Condition-specific Nephrology note types — kidney function and injury.
//
// CKD assessment (KDIGO 2024 CGA classification and risk), acute kidney injury
// (KDIGO 2012 definition and staging), glomerular disease, diabetic kidney
// disease and hypertensive kidney disease. Every template reuses the shared
// Nephrology field builders so history, examination, serum/urine results and
// radiology behave exactly as in the nine core Nephrology notes.
//
// The KDIGO panel (type "kdigo_renal") is the only place a category, an AKI
// stage or a kidney-failure risk is produced, and it produces them solely from
// values the clinician documented — including the evidence of chronicity that
// CKD requires. Where that evidence is absent the panel states that CKD is not
// established instead of assigning a stage.

