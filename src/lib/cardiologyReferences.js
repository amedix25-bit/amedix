const BY_ID = new Map(CARDIOLOGY_REFERENCES.map((r) => [r.id, r]));

export const getCardiologyReference = (id) => BY_ID.get(id) || null;

export const cardiologyCitation = (id) => {
  const r = getCardiologyReference(id);
  if (!r) return "";
  return `${r.organization} — ${r.title}, ${r.version} (${r.url})`;
};

