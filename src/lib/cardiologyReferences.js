// Cardiology guideline register.
//
// Every guideline cited by a Cardiology note, by a decision-support prompt or by
// the PDF export is registered here once, with the edition that was current when
// the register was compiled (2026-10-30). Notes and prompts reference a guideline
// by id — they never carry a hand-typed citation — so an edition can be updated in
// one place and every note inherits the corrected citation.
//
// The edition and year are recorded exactly as the issuing body published them.
// The links point at the issuing body's guideline index rather than a deep link,
// because deep links change with every republication. AMedix cardiology sign-off
// is still required before a prompt that relies on a threshold is used
// clinically — that state is carried on each rule, not assumed here.
//
// The four references required for Cardiology documentation are mandatory and are
// integrated into the note content itself (history, assessment, classification,
// monitoring), not merely listed:
//   ESC   — European Society of Cardiology clinical practice guidelines
//   ACC   — American College of Cardiology guidelines
//   AHA   — American Heart Association guidelines
//   WHO   — ICD-11 MMS, Chapter 11 (Diseases of the circulatory system)

