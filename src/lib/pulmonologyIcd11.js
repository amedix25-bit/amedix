const RESPIRATORY_DOMAINS = ["respiratory", "respiratory_failure", "pleural", "airway", "thromboembolic"];

// The respiratory subset of the verified catalogue, plus any entry whose own
// domain names a respiratory condition.
export const PULMONOLOGY_ICD11 = EMERGENCY_ICD11.filter(
  (item) =>
    RESPIRATORY_DOMAINS.includes(item.domain) ||
    /^C[AB]\d/i.test(item.code || "") ||
    /respirat|pulmon|pleural|asthma|copd|apnoea/i.test(item.display || ""),
);

