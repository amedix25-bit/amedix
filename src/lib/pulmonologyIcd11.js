// Pulmonology / Respiratory Medicine — ICD-11 coding context.
//
// WHERE THE CODES COME FROM
// This module does not type a single ICD-11 code of its own. The respiratory
// entries it offers are the ones already carried by the AMedix verified
// emergency catalogue subset (release recorded, WHO browser as the source of
// verification); everything else is left to the live WHO ICD-11 API search and
// the WHO browser, and is stored by the clinician as review required.
//
// A code is never a diagnosis. Selecting a category records a SUSPECTED
// diagnosis carrying its release, WHO entity URI and retrieval time; only the
// clinician documents confirmation, the clinical basis and the detail the code
// cannot carry.
//
// Postcoordination is not generated by AMedix: a cluster is entered exactly as
// the WHO Coding Tool shows it, and is stored as review required until it is
// checked.

