// TWO KINDS OF SOURCE, KEPT APART ON PURPOSE
//   · INTERNATIONAL RECOMMENDATIONS — published by a professional or global body.
//     The European Association of Urology (EAU) is the PRIMARY urological reference
//     for this portal; AUA, ESMO, NCCN, KDIGO, ESHRE, the ICS and WHO provide the
//     additional guidance named beside each topic. They are documentation support:
//     they never become the local rule of the institution.
//   · LOCALLY APPROVED PROTOCOLS — the institution's own adopted version, with an
//     approving body, an approval reference and a review date. AMedix holds NONE by
//     default (see URO_LOCAL_PROTOCOLS), and every note says so plainly, so a local
//     protocol is never implied where none has been approved.
//
// HONESTY RULES APPLIED TO THIS REGISTER
//   · Only guidance that actually exists is named, with the issuing body's own URL.
//   · A publication year, version or update date is recorded ONLY when it can be
//     confirmed from the issuing body. EAU, AUA, NCCN and ESMO revise their
//     guidelines continuously, so those fields are deliberately left EMPTY and the
//     entry is marked `under_review`: the clinician is told to confirm the edition
//     in force at the source instead of being shown a date AMedix cannot verify.
//   · `last_verified_date` records when the register entry itself was checked
//     against the issuing body's page — not when the guideline was published.
//   · AMedix links to the issuing body and never copies or redistributes the
//     document.
//
// No recommendation text, threshold or algorithm is transcribed into the app: the
// note records WHAT it documents against, and the clinician reads the source.

