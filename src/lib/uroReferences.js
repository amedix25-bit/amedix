// The evidence basis recorded WITH the note, so an exported record keeps it.
export const uroGuidanceBasis = (noteKey) => {
  const refs = guidanceForUroNote(noteKey);
  const primary = refs.filter((r) => r.primary);
  const other = refs.filter((r) => !r.primary);
  const names = (rows) => rows.map((r) => `${r.issuing_organization} — ${r.title}`).join("; ");
  return [
    primary.length ? `Primary international reference: ${names(primary)}.` : "",
    other.length ? `Additional international guidance: ${names(other)}.` : "",
    "Diagnosis coding: WHO ICD-11 MMS, read from the central AMedix ICD-11 service with its release recorded on each code.",
    URO_LOCAL_PROTOCOL_NOTICE,
    "The note records what its documentation follows; no recommendation text is transcribed and no local approval is implied.",
  ]
    .filter(Boolean)
    .join(" ");
};

